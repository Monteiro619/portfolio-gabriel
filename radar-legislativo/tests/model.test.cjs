const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const M = require('../model.js');
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../snapshot.js'), 'utf8'), context);
const raw = JSON.parse(JSON.stringify(context.window.RADAR_SNAPSHOT));
const records = raw.records.map(M.record);
assert.equal(records.length, 40);
assert.equal(new Set(records.map(p=>p.id)).size, records.length);
assert.ok(records.every(p=>p.ementa && p.autores.length && p.tramitacoes.length));
assert.ok(records.some(p=>p.siglaTipo==='PEC'));
assert.ok(M.filter(records,{ano:2025}).every(p=>p.ano===2025));
assert.equal(M.filter(records,{numero:records[0].numero,ano:records[0].ano,tipo:records[0].siglaTipo})[0].id, records[0].id);
const query = new URL('https://example.test'+M.query({ano:2026,tipo:'PL',numero:123,q:'proteção de dados',autor:'João "Silva"'},2));
assert.equal(query.searchParams.get('keywords'),'proteção de dados');
assert.equal(query.searchParams.get('autor'),'"João Silva"');
assert.equal(query.searchParams.get('pagina'),'2');
assert.equal(query.searchParams.get('ordenarPor'),'id');
const original = records[0], changed = structuredClone(original);
assert.deepEqual(M.compare(original,changed),{statusChanged:false,events:[]});
changed.status.descricaoSituacao='Situação de teste';
changed.tramitacoes.unshift({dataHora:'2099-01-01T12:00',sequencia:999,siglaOrgao:'TESTE',descricaoTramitacao:'Evento de teste',descricaoSituacao:'',despacho:''});
assert.equal(M.compare(original,changed).events.length,1);
assert.equal(M.compare(original,changed).statusChanged,true);
changed.tramitacoes.reverse();
assert.equal(M.compare(original,changed).events.length,1);
const watched = {record:original,addedAt:new Date().toISOString(),checkedAt:'',priority:'Alta',notes:'Nota; com "aspas"',changes:[]};
const restored=M.validateBackup(JSON.parse(JSON.stringify({version:1,items:[watched]})));
assert.equal(restored[0].record.id,original.id);
assert.equal(restored[0].notes,watched.notes);
assert.deepEqual(restored[0].record.status,original.status);
assert.throws(()=>M.validateBackup({version:1,items:[watched,watched]}),/repetidas/);
assert.throws(()=>M.validateBackup({version:2,items:[]}),/incompatível/);
assert.throws(()=>M.record({id:'javascript:1'}),/inválido/);
assert.equal(M.safeLink('javascript:alert(1)'), '');
assert.equal(M.safeLink('https://camara.leg.br.evil.test/x'), '');
assert.equal(M.safeLink('https://www.camara.leg.br/x'),'https://www.camara.leg.br/x');
assert.ok(M.csv([original]).includes(M.label(original)));
console.log('OK: base oficial, consultas, filtros, comparação, links, backup e CSV.');
