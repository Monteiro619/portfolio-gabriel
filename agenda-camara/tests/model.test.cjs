const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const M=require('../model.js');
const context={window:{}};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../snapshot.js'),'utf8'),context);
const snapshot=JSON.parse(JSON.stringify(context.window.AGENDA_SNAPSHOT));
const events=snapshot.events.map(M.event);
assert.ok(events.length>0);assert.equal(new Set(events.map(e=>e.id)).size,events.length);
assert.deepEqual(M.period('2026-10-14','week'),{start:'2026-10-12',end:'2026-10-18'});
assert.deepEqual(M.period('2024-02-15','month'),{start:'2024-02-01',end:'2024-02-29'});
assert.equal(M.shift('2026-12-31',1),'2027-01-01');
assert.throws(()=>M.date('2026-02-30'),/válida/);
assert.throws(()=>M.validateRange('2026-10-14','2026-10-13'),/final/);
assert.throws(()=>M.validateRange('2026-01-01','2026-12-31'),/93/);
assert.equal(M.group({sigla:'PLEN',codTipoOrgao:26,tipoOrgao:'Plenário Virtual'}),'plenario');
assert.equal(M.group({sigla:'CE',codTipoOrgao:2,tipoOrgao:'Comissão Permanente'}),'comissoes');
assert.equal(M.group({sigla:'CN',codTipoOrgao:81001,tipoOrgao:'Órgão do Congresso Nacional'}),'outros');
assert.equal(M.group({sigla:'MESA',codTipoOrgao:1,tipoOrgao:'Comissão Diretora'}),'outros');
assert.ok(M.filter(events,{category:'comissoes'}).every(e=>e.groups.includes('comissoes')));
const plenary=events.find(e=>e.groups.includes('plenario'));assert.ok(plenary);
assert.ok(M.filter(events,{organ:180}).every(e=>e.organs.some(o=>o.id===180)));
const q=new URL('https://example.test'+M.query('2026-10-12','2026-10-18',2));
assert.equal(q.searchParams.get('dataInicio'),'2026-10-12');assert.equal(q.searchParams.get('pagina'),'2');
const e=events[0],serialized={version:1,items:[{event:e,notes:'Notas; com "aspas"',checkedAt:''}]};
assert.deepEqual(M.backup(JSON.parse(JSON.stringify(serialized))),serialized.items);
assert.throws(()=>M.backup({version:1,items:[serialized.items[0],serialized.items[0]]}),/repetidos/);
assert.equal(M.safeLink('javascript:alert(1)'), '');
assert.equal(M.safeLink('https://www.youtube.com/watch?v=x',true),'https://www.youtube.com/watch?v=x');
assert.equal(M.safeLink('https://camara.leg.br.evil.test/'),'');
const a={...e,id:1,start:'2026-10-14T10:00',end:'2026-10-14T11:00',day:'2026-10-14',status:'Convocada'};
const b={...a,id:2,start:'2026-10-14T10:30',end:'2026-10-14T11:30'};
assert.deepEqual(M.overlaps([a,b]),[[1,2]]);
assert.deepEqual(M.overlaps([a,{...b,status:'Cancelada'}]),[]);
assert.deepEqual(M.overlaps([a,{...b,end:''}]),[]);
assert.deepEqual(M.overlaps([{...a,end:''},{...b,start:a.start,end:''}]),[[1,2]]);
const calendar=M.ics([{...a,description:'Texto com acentuação; vírgula, e\nlinha. '+ 'ação '.repeat(40)}]);
assert.ok(calendar.includes('DTSTART;TZID=America/Sao_Paulo:20261014T100000'));
assert.ok(calendar.includes('DTEND;TZID=America/Sao_Paulo:20261014T110000'));
assert.ok(calendar.includes('BEGIN:VTIMEZONE'));
assert.ok(calendar.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
assert.ok(!M.ics([{...a,end:''}]).includes('DTEND'));
assert.ok(M.ics([{...a,status:'Cancelada'}]).includes('STATUS:CANCELLED'));
const pauta=M.agenda({ordem:1,proposicao_:{id:123,siglaTipo:'PL',numero:10,ano:2026,ementa:'Texto'},relator:{nome:'Relator de teste'}});
assert.equal(pauta.propositionLabel,'PL 10/2026');assert.equal(pauta.propositionId,123);
const related=M.agenda({proposicao_:{id:1,siglaTipo:'PRL',numero:8,ano:0},proposicaoRelacionada_:{id:2,siglaTipo:'PL',numero:4000,ano:2012}});
assert.equal(related.propositionLabel,'PL 4000/2012');assert.equal(related.propositionId,2);
assert.equal(M.agenda({proposicao_:{id:1,siglaTipo:'PRL',numero:8,ano:0}}).propositionLabel,'PRL 8');
assert.ok(M.csv([a]).includes('Início (Brasília)'));
console.log('OK: dados oficiais, períodos, categorias, filtros, backup, conflitos, pauta, ICS e CSV.');
